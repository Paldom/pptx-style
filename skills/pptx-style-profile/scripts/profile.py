#!/usr/bin/env python3
"""Profile a PowerPoint template into a style contract (contract.json + STYLE.md).

    python3 profile.py TEMPLATE.pptx|.potx [--out DIR] [--thumbs] [--self-test]

Writes DIR/contract.json (machine contract, hashed) and DIR/STYLE.md (human guide
generated from the contract - never edit it by hand). Default DIR is
.pptx-style/<template-slug>/ under the current directory. With --thumbs and
LibreOffice installed, renders the template's slides into DIR/thumbs/.
Exit codes: 0 ok, 1 profiling failed, 2 usage error.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pptx_core as core


def emu_to_cm(v) -> str:
    return f"{v / 360000:.1f}"


def box_cm(b) -> str:
    return (
        "-"
        if not b
        else f"x{emu_to_cm(b[0])} y{emu_to_cm(b[1])} w{emu_to_cm(b[2])} h{emu_to_cm(b[3])} cm"
    )


def slot_summary(slots: dict) -> str:
    """'`title` text, `mark1`..`mark18` mark x18' - runs of one kind collapse."""
    out, run = [], []

    def flush():
        if len(run) > 3:
            out.append(f"`{run[0][0]}`..`{run[-1][0]}` {run[0][1]} x{len(run)}")
        else:
            out.extend(f"`{k}` {kind}" for k, kind in run)
        run.clear()

    for k, v in slots.items():
        if run and run[-1][1] != v["kind"]:
            flush()
        run.append((k, v["kind"]))
    flush()
    return ", ".join(out)


def style_md(c: dict) -> str:
    """Render the human guide from the contract. Everything here is derived, nothing invented."""
    L: list[str] = []
    src = c["source"]
    L += [
        f"# Style guide: {src['file']}",
        "",
        f"Generated by {c['tool']} from the template file itself (sha256 `{src['sha256'][:16]}…`).",
        "Do not edit by hand: re-run the profiler. Values marked *inferred* come from the",
        "sample slides and list their evidence; everything else is read from the file.",
        "",
        "## Theme",
        "",
        "| Slot | Hex |",
        "| --- | --- |",
    ]
    L += [f"| {k} | #{v} |" for k, v in c["theme"]["colors"].items()]
    f = c["theme"]["fonts"]
    L += ["", f"Fonts: headings **{f.get('major')}**, body **{f.get('minor')}**.", ""]
    ts = c["theme"]["text_styles"]
    L += [f"Master sizes (pt): title {ts.get('titleStyle')}, body {ts.get('bodyStyle')}.", ""]
    d = c["derived"]
    weak = [r for r in d["contrast"] if not r["aa_text"] and r["on"] in ("lt1", "dk1")]
    if weak:
        L += [
            "Colours below WCAG AA 4.5:1 as normal text (fills or large text only): "
            + ", ".join(f"{r['fg']} on {r['on']} ({r['ratio']}:1)" for r in weak),
            "",
        ]
    L += ["## Layouts (use these names in a build spec)", ""]
    L += [
        "| Layout | Fill keys (capacity lines x chars) | Sample slide | Notes |",
        "| --- | --- | --- | --- |",
    ]
    for lay in c["layouts"]:
        keys = ", ".join(
            f"`{p['key']}`"
            + (f" {p['capacity'][0]}x{p['capacity'][1]}" if p.get("capacity") else "")
            for p in lay["placeholders"]
        )
        notes = []
        if lay["collision_group"]:
            notes.append(
                "same signature as "
                + ", ".join(n for n in lay["collision_group"] if n != lay["name"])
            )
        if lay["art"]["background"] == "image" or lay["art"]["pictures"]:
            notes.append("art lives on the layout")
        for p in lay["placeholders"]:
            if p["prompt_looks_like_content"]:
                notes.append(f"`{p['key']}` prompt {p['prompt']!r} is NOT content: fill it")
        L.append(
            f"| {lay['name']} | {keys or '-'} | {'yes' if lay['has_sample_slide'] else 'no'} | {'; '.join(notes)} |"
        )
    L += ["", "## Patterns (sample slides to clone and re-text)", ""]
    L += [
        "| Pattern id | Slide | Layout | Slots | Repeat groups |",
        "| --- | --- | --- | --- | --- |",
    ]
    for p in c["patterns"]:
        slots = slot_summary(p["slots"])
        reps = ", ".join(
            f"`{k}` x{v['count']} ({', '.join(s['tag'] for s in v['slots'])})"
            for k, v in p["repeats"].items()
        )
        note = (
            " (asset bank: pictures only, do not clone as content)" if p.get("asset_bank") else ""
        )
        note += " (hidden slide)" if p.get("hidden") else ""
        L.append(
            f"| `{p['id']}`{note} | {p['slide']} | {p['layout']} | {slots or '-'} | {reps or '-'} |"
        )
    L += ["", "## Chrome (never move, cover or retype)", ""]
    for m in c["masters"]:
        for ch in m["chrome"]:
            L.append(f"- master: {ch['role']} ({ch['kind']} {ch['name']!r}) at {box_cm(ch['box'])}")
    for lay in c["layouts"]:
        for ch in lay["chrome"]:
            if not ch["placeholder"]:
                L.append(
                    f"- layout {lay['name']!r}: {ch['role']} ({ch['kind']} {ch['name']!r}) at {box_cm(ch['box'])}"
                )
    L += [
        "",
        "## Inferred rules (evidence: sample slides)",
        "",
        f"- *inferred* type scale (pt): {d['type_scale']}; smallest text in samples {d['min_font_size']} pt",
        f"- *inferred* content safe area: {box_cm(d['safe_area'])}; footer band: {box_cm(d['footer_band'])}",
        f"- colours used on samples: {', '.join('#' + k for k in d['colors_used']) or 'theme references only'}",
        f"- off-theme colours: {', '.join('#' + k for k in d['off_theme_colors']) or 'none'}",
        "",
        "## AI-readiness findings (for the template owner)",
        "",
    ]
    if not c["ai_readiness"]:
        L.append("None.")
    for a in c["ai_readiness"]:
        L.append(
            f"- **{a['severity']}** `{a['code']}` {a['where']}: {a['message']}. Fix: {a['fix']}."
        )
    return "\n".join(L) + "\n"


def run(template: Path, out: Path, thumbs: bool) -> dict:
    contract = core.profile(template)
    contract["source"]["path"] = str(template.resolve())
    out.mkdir(parents=True, exist_ok=True)
    (out / "contract.json").write_text(
        json.dumps(contract, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (out / "STYLE.md").write_text(style_md(contract), encoding="utf-8")
    if thumbs:
        r = core.render(template, out / "thumbs")
        print(f"thumbs: {r['status']} {r.get('reason', '')}".rstrip())
    return contract


def summary(c: dict, out: Path) -> str:
    sev: dict[str, int] = {}
    for a in c["ai_readiness"]:
        sev[a["severity"]] = sev.get(a["severity"], 0) + 1
    return (
        f"profiled {c['source']['file']} ({c['source']['kind']}): {len(c['layouts'])} layouts, "
        f"{len(c['patterns'])} patterns, theme fonts {c['theme']['fonts']}\n"
        f"AI-readiness: {sev or 'clean'}\n"
        f"wrote {out / 'contract.json'} and {out / 'STYLE.md'}"
    )


def self_test() -> int:
    """Fixture-free checks of the core invariants (the full suite lives in the repo's tests/)."""
    xml = (
        b'<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" '
        b'xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006" '
        b'xmlns:p14="http://schemas.microsoft.com/office/powerpoint/2010/main" mc:Ignorable="p14"><p:cSld/></p:sld>'
    )
    root, decls = core.parse_xml(xml)
    out = core.dump_xml(root, decls)
    assert b"xmlns:p14=" in out and b'mc:Ignorable="p14"' in out and b"ns0:" not in out, out
    rels = b'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="t" Target="x"/></Relationships>'
    assert b'<Relationships xmlns="' in core.dump_xml(*core.parse_xml(rels))
    assert core.contrast("000000", "FFFFFF") == 21.0
    assert core.resolve("ppt/slides/slide1.xml", "../media/image1.png") == "ppt/media/image1.png"
    assert core.relative("ppt/slides/slide1.xml", "ppt/media/image1.png") == "../media/image1.png"
    ph = {"key": "body", "type": "obj", "box": [0, 0, 10, 10]}
    old = {
        "slide_size": [1, 1],
        "layouts": [{"name": "A", "placeholders": [ph], "chrome": []}],
        "patterns": [],
        "theme": {"colors": {"accent1": "000000"}, "fonts": {}},
    }
    new = json.loads(json.dumps(old))
    new["layouts"][0]["name"] = "B"
    assert core.diff_contracts(old, new)["breaking"] == [
        "layout 'A' renamed to 'B' (add an alias or update specs)"
    ]
    md = style_md({**core_minimal(), "source": {"file": "t.pptx", "sha256": "0" * 64}})
    assert md.startswith("# Style guide: t.pptx")
    print("self-test OK")
    return 0


def core_minimal() -> dict:
    return {
        "tool": "test",
        "theme": {"colors": {"dk1": "000000"}, "fonts": {}, "text_styles": {}},
        "derived": {
            "contrast": [],
            "type_scale": {},
            "min_font_size": None,
            "safe_area": None,
            "footer_band": None,
            "colors_used": {},
            "off_theme_colors": [],
        },
        "layouts": [],
        "patterns": [],
        "masters": [],
        "ai_readiness": [],
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("template", nargs="?")
    ap.add_argument("--out", help="output folder (default .pptx-style/<slug>/)")
    ap.add_argument(
        "--thumbs", action="store_true", help="render slide thumbnails with LibreOffice"
    )
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not a.template:
        ap.print_usage()
        return 2
    t = Path(a.template)
    if not t.is_file() or t.suffix.lower() not in (".pptx", ".potx"):
        print(
            f"error: {t} is not a .pptx/.potx file (macro-enabled and binary .ppt are not supported)",
            file=sys.stderr,
        )
        return 2
    out = Path(a.out) if a.out else Path(".pptx-style") / core.slug(t.stem, 40)
    try:
        c = run(t, out, a.thumbs)
    except Exception as exc:  # report, never a traceback wall
        print(f"error: could not profile {t}: {exc}", file=sys.stderr)
        return 1
    print(summary(c, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
